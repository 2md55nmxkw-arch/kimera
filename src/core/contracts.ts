// Договорённости между модулями. Всё, что здесь описано, — общее для всех;
// меняя этот файл, проверь каждого, кто им пользуется.
//
// Как устроен кадр:
//   1. main.ts собирает Frame: время, положение прокрутки, указатель.
//   2. Каждая часть (Part) делает свой шаг: сцена, актёр, след, состояние шкур.
//   3. Сцена рендерится один раз в G-буфер (core/gbuffer.ts): цвет, нормаль, глубина, метки.
//   4. Композит (skins/index.ts) считает из G-буфера все шкуры и сшивает их линзой.
//
// Правила, на которых держатся контрольные кадры (core/capture.ts):
//   · в шаге нет часов, прокрутки и мыши — только то, что пришло во Frame;
//   · случайное берётся из core/random.ts, не из Math.random;
//   · у всего, что копит состояние между кадрами, есть reset().

/** Указатель: сглаженное положение линзы и цель, к которой оно идёт. Доли экрана от левого верхнего угла. */
export interface Pointer {
  x: number;
  y: number;
  tx: number;
  ty: number;
  /** 0…1, сглаженное зажатие. */
  press: number;
  pressTarget: number;
  /** Когда указатель двигали в последний раз, мс по performance.now(). */
  lastMove: number;
}

/** Что шаг симуляции получает снаружи вместо часов, прокрутки и мыши. */
export interface StepEnv {
  /** Положение прокрутки в главах: 0 — первая, 1 — вторая… */
  s: number;
  /** Включено «уменьшение движения». */
  still: boolean;
  /** Курсор давно не двигался: линза бродит сама. */
  roam: boolean;
}

/** Всё, что известно о текущем кадре. Собирается в main.ts, частям приходит готовым. */
export interface Frame {
  dt: number;
  /** Своё время сцены, секунды. Замирает при «уменьшении движения». */
  t: number;
  still: boolean;
  /** Положение прокрутки в главах, уже зажатое в 0…COUNT−1. */
  s: number;
  /** Глава, чья полоса сейчас идёт. Полоса центрирована на секции главы. */
  chapter: number;
  /** Место внутри полосы, 0…1: в начале линза появляется, к концу заливает экран. */
  q: number;
  /** Ширина экрана к высоте. */
  aspect: number;
  /** Где по горизонтали стоит персонаж, 0…1. */
  subjectX: number;
  pointer: Pointer;
  /** Радиус линзы в покое, доли высоты экрана. */
  lensRest: number;
}

/**
 * Часть сцены со своим состоянием. Новая механика — новая часть в своём файле,
 * подключённая одной строкой в main.ts.
 */
export interface Part {
  /** Вернуться к состоянию сразу после загрузки. */
  reset?(): void;
  /** Шаг симуляции. */
  step?(frame: Frame): void;
}
